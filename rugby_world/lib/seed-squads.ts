function makePlayers(teamId: string, unionId: string, rows: PlayerSeed[], bios: string): Player[] {
  return rows.map(([number, name, position, club, caps, tries, heightCm, weightKg, dob, status]) => ({
    id: `pl-${teamId}-${number}`,
    teamId,
    unionId,
    name,
    position,
    number,
    club,
    caps,
    tries,
    heightCm,
    weightKg,
    dob,
    status: status ?? "available",
    bio: bios,
  }));
}

